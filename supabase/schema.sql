-- QR-ATT Phase 3
-- Supabase Database Schema

-- ==========================================
-- PROFILES
-- ==========================================

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'student'
    check (role in ('student', 'teacher')),
  student_id text unique,
  created_at timestamptz not null default now()
);

-- ==========================================
-- EVENTS
-- ==========================================

create table if not exists public.events (
  event_id text primary key,
  title text not null,
  start_time timestamptz not null,
  end_time timestamptz not null,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

-- ==========================================
-- ATTENDANCE
-- ==========================================

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  event_id text not null references public.events(event_id) on delete cascade,
  scanned_at timestamptz not null default now(),

  unique (student_id, event_id)
);

-- ==========================================
-- ROW LEVEL SECURITY
-- ==========================================

alter table public.profiles enable row level security;
alter table public.events enable row level security;
alter table public.attendance enable row level security;

-- ==========================================
-- PROFILES POLICIES
-- ==========================================

create policy "Users can view own profile"
on public.profiles
for select
to authenticated
using (auth.uid() = id);

create policy "Users can insert own profile"
on public.profiles
for insert
to authenticated
with check (auth.uid() = id);

create policy "Users can update own profile"
on public.profiles
for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

-- ==========================================
-- EVENTS POLICIES
-- ==========================================

create policy "Authenticated users can view events"
on public.events
for select
to authenticated
using (true);

create policy "Teachers can create events"
on public.events
for insert
to authenticated
with check (
  auth.uid() = created_by
  and exists (
    select 1
    from public.profiles
    where profiles.id = auth.uid()
      and profiles.role = 'teacher'
  )
);

create policy "Teachers can update own events"
on public.events
for update
to authenticated
using (auth.uid() = created_by)
with check (auth.uid() = created_by);

create policy "Teachers can delete own events"
on public.events
for delete
to authenticated
using (auth.uid() = created_by);

-- ==========================================
-- ATTENDANCE POLICIES
-- ==========================================

create policy "Students can view own attendance"
on public.attendance
for select
to authenticated
using (auth.uid() = student_id);

create policy "Students can record own attendance"
on public.attendance
for insert
to authenticated
with check (auth.uid() = student_id);

create policy "Teachers can view attendance for own events"
on public.attendance
for select
to authenticated
using (
  exists (
    select 1
    from public.events
    where events.event_id = attendance.event_id
      and events.created_by = auth.uid()
  )
);